import java.security.MessageDigest

val componentDirectory = layout.projectDirectory.dir("src/main/kotlin/dev/s7a/strata/component")
val componentInputs = listOf("ProfileComponents.kt", "TextInputComponents.kt", "CanvasComponents.kt", "TiledImageComponents.kt", "VirtualListComponents.kt", "SelectionListComponents.kt").map { componentDirectory.file(it).asFile }
val componentCompileDirectory = layout.projectDirectory.dir("src/test/kotlin/dev/s7a/strata/component")
val componentCompatibilityDirectory = layout.projectDirectory.dir("src/jvmMain/kotlin/dev/s7a/strata/component")
val generatedMarker = "// Generated by :api:generateStateComponentOverloads. Do not edit by hand."
val reactiveParameters = mapOf(
    "ProgressBar" to setOf("progress"),
    "Image" to setOf("source"),
    "PlayerHead" to setOf("source"),
    "Canvas" to setOf("source"),
    "TiledImage" to setOf("source"),
    "Slot" to setOf("bind", "highlightable"),
    "Button" to setOf("label", "enabled"),
    "Tab" to setOf("label", "selected", "enabled"),
    "Checkbox" to setOf("label", "enabled"),
    "Slider" to setOf("label", "enabled"),
    "CycleButton" to setOf("label", "enabled"),
    "TextField" to setOf("enabled"),
    "TextArea" to setOf("enabled"),
    "VirtualList" to setOf("items", "canLoadLeading", "canLoadTrailing"),
    "SelectionList" to setOf("items", "canLoadLeading", "canLoadTrailing"),
)

/** Selects the public source surface, compile checks, or removable JVM binary bridges. */
enum class StateComponentOutput {
    OVERLOADS,
    COMPILE_CASES,
    JVM_BRIDGES,
}

/** Generates every nonempty reactive-argument combination from the maintained literal declarations. */
fun stateComponentOverloads(output: StateComponentOutput = StateComponentOutput.OVERLOADS): Map<String, String> {
    val compileCases = output == StateComponentOutput.COMPILE_CASES
    val compatibility = output == StateComponentOutput.JVM_BRIDGES
    val directCall = compileCases || compatibility
    val inputs = componentInputs.map { it.readText().replace("\r\n", "\n") }
    val declarations = Regex("(?m)^public fun (?:(<[^\\n]+>) )?UiScope\\.(\\w+)\\(\\n([\\s\\S]*?)^\\) \\{")
    return reactiveParameters.keys.associateWith { component ->
        val functions = buildString {
            inputs.forEach { source ->
                declarations.findAll(source).forEach declaration@{ match ->
                    val generics = match.groupValues[1]
                    val name = match.groupValues[2]
                    if (name != component) return@declaration
                    val selected = reactiveParameters[name] ?: return@declaration
                    val parameters = match.groupValues[3].trimEnd().lines().map { line ->
                        check(line.startsWith("    ") && line.trim().endsWith(",")) { "Unsupported component parameter layout: $name: $line" }
                        line.trim().removeSuffix(",")
                    }
                    val names = parameters.map { it.substringBefore(":") }
                    if (name == "PlayerHead" && "scale" !in names) return@declaration
                    val reactive = names.filter { it in selected }
                    check(reactive.isNotEmpty()) { "Reactive component $name has no selected parameters." }
                    val identity = "$name:$generics:${parameters.joinToString { it.substringAfter(": ").substringBefore(" = ") }}"
                    val signature = MessageDigest.getInstance("SHA-256").digest(identity.toByteArray()).take(6).joinToString("") { "%02x".format(it) }
                    for (mask in 1 until (1 shl reactive.size)) {
                        val sources = reactive.filterIndexed { index, _ -> mask and (1 shl index) != 0 }
                        appendLine()
                        if (compatibility) {
                            appendLine("/**")
                            appendLine(" * JVM binary compatibility bridge for [$name], scheduled for removal in 1.0.0.")
                            appendLine(" */")
                            appendLine("@Deprecated(")
                            appendLine("    message = \"Recompile against the $name overloads. Scheduled for removal in 1.0.0.\",")
                            appendLine("    replaceWith = ReplaceWith(\"$name(${names.joinToString { "$it = $it" }})\", \"dev.s7a.strata.component.$name\"),")
                            appendLine("    level = DeprecationLevel.HIDDEN,")
                            appendLine(")")
                        } else if (compileCases.not()) {
                            appendLine("/**")
                            appendLine(" * Observes ${sources.joinToString()} for [$name] at the next owner-thread frame cutoff.")
                            appendLine(" *")
                            appendLine(" * Retain caller-owned sources and editing state outside reevaluation.")
                            appendLine(" * See [Observe] for shared snapshots, equal-value suppression, and cleanup; literal arguments follow [$name].")
                            appendLine(" * Modifiers and parent data apply to the actual component, while the binding owns its sibling key.")
                            appendLine(" */")
                        }
                        if (compileCases.not()) appendLine("@JvmName(\"${name}State${signature}_$mask\")")
                        val functionName = when (output) {
                            StateComponentOutput.OVERLOADS -> name
                            StateComponentOutput.COMPILE_CASES -> "compile${name}${signature}_$mask"
                            StateComponentOutput.JVM_BRIDGES -> "legacy${name}${signature}_$mask"
                        }
                        appendLine("${if (compileCases) "private" else "public"} fun ${if (generics.isEmpty()) "" else "$generics "}UiScope.$functionName(")
                        parameters.forEachIndexed { index, parameter ->
                            val parameterName = names[index]
                            if (parameterName in sources) {
                                val type = parameter.substringAfter(": ").substringBefore(" = ")
                                appendLine("    $parameterName: StateSource<$type>,")
                            } else {
                                appendLine("    $parameter,")
                            }
                        }
                        appendLine(") {")
                        if (directCall.not()) appendLine("    emitObservedComponent(listOf(${sources.joinToString()}), key) { values ->")
                        val callIndent = if (directCall) "    " else "        "
                        appendLine("$callIndent$name(")
                        parameters.forEachIndexed { index, parameter ->
                            val parameterName = names[index]
                            val sourceIndex = sources.indexOf(parameterName)
                            val expression = when {
                                directCall -> parameterName
                                parameterName == "key" -> "null"
                                sourceIndex < 0 -> parameterName
                                else -> "values[$sourceIndex] as ${parameter.substringAfter(": ").substringBefore(" = ")}"
                            }
                            appendLine("$callIndent    $parameterName = $expression,")
                        }
                        appendLine("$callIndent)")
                        if (directCall.not()) appendLine("    }")
                        appendLine("}")
                    }
                }
            }
        }
        check(functions.isNotEmpty()) { "Missing generated component: $component" }
        val imports = inputs.flatMap { source -> source.lineSequence().filter { it.startsWith("import ") }.toList() }
            .filter { line -> Regex("\\b${Regex.escape(line.substringAfterLast('.'))}\\b").containsMatchIn(functions) }
            .plus("import dev.s7a.strata.state.StateSource")
            .plus(if (compileCases) emptyList() else listOf("import kotlin.jvm.JvmName"))
            .plus(if (compatibility) listOf("import kotlin.jvm.JvmMultifileClass") else emptyList()).distinct().sorted()
        buildString {
            appendLine(generatedMarker)
            if (compatibility) {
                // Keep old compiled callers linked until the scheduled bridge removal.
                appendLine("@file:JvmName(\"ObservedComponentsKt\")")
                appendLine("@file:JvmMultifileClass")
            }
            appendLine("@file:Suppress(\"FunctionNaming\", \"ktlint:standard:function-naming\", \"LongParameterList\", \"TooManyFunctions\", \"UNCHECKED_CAST\", \"unused\")")
            appendLine()
            appendLine("package dev.s7a.strata.component")
            appendLine()
            imports.forEach(::appendLine)
            append(functions)
        }
    }
}

/** Lists only outputs owned by this generator, including obsolete component files. */
fun generatedStateComponentFiles() = listOf(componentDirectory.asFile, componentCompileDirectory.asFile, componentCompatibilityDirectory.asFile).flatMap { directory ->
    directory.listFiles().orEmpty().filter { file ->
        file.isFile && file.extension == "kt" && file.useLines { it.firstOrNull() == generatedMarker }
    }
}

/** Maps each component to its source overloads, compilation cases, and removable JVM bridges. */
fun stateComponentOutputs() = stateComponentOverloads().mapKeys { (name, _) -> componentDirectory.file("Observed${name}Components.kt").asFile } +
    stateComponentOverloads(StateComponentOutput.COMPILE_CASES).mapKeys { (name, _) -> componentCompileDirectory.file("Observed${name}CompileCases.kt").asFile } +
    stateComponentOverloads(StateComponentOutput.JVM_BRIDGES).mapKeys { (name, _) -> componentCompatibilityDirectory.file("LegacyObserved${name}Components.kt").asFile }

tasks.register("generateStateComponentOverloads") {
    group = "generation"
    description = "Generates typed literal/source combinations for reactive component inputs."
    inputs.files(componentInputs)
    inputs.file(layout.projectDirectory.file("state-components.gradle.kts"))
    outputs.files(reactiveParameters.keys.map { componentDirectory.file("Observed${it}Components.kt") })
    outputs.files(reactiveParameters.keys.map { componentCompileDirectory.file("Observed${it}CompileCases.kt") })
    outputs.files(reactiveParameters.keys.map { componentCompatibilityDirectory.file("LegacyObserved${it}Components.kt") })
    outputs.upToDateWhen { generatedStateComponentFiles().toSet() == stateComponentOutputs().keys }
    doLast {
        val outputs = stateComponentOutputs()
        outputs.keys.forEach { file ->
            check(file.exists().not() || file.useLines { it.firstOrNull() == generatedMarker }) {
                "Refusing to overwrite a handwritten component file: $file"
            }
        }
        generatedStateComponentFiles().filter { it !in outputs }.forEach { file ->
            check(file.delete()) { "Could not remove obsolete generated file: $file" }
        }
        outputs.forEach { (file, content) ->
            file.parentFile.mkdirs()
            file.writeText(content, Charsets.UTF_8)
        }
    }
}
val checkStateComponentOverloads = tasks.register("checkStateComponentOverloads") {
    group = "verification"
    description = "Checks reactive component generation without changing tracked sources."
    inputs.files(componentInputs)
    inputs.file(layout.projectDirectory.file("state-components.gradle.kts"))
    inputs.files(provider { generatedStateComponentFiles() })
    doLast {
        val outputs = stateComponentOutputs()
        check(generatedStateComponentFiles().toSet() == outputs.keys && outputs.all { (file, content) ->
            file.readText().replace("\r\n", "\n") == content
        }) {
            "Reactive component overloads or compile cases are missing, unexpected, or stale. Run :api:generateStateComponentOverloads."
        }
    }
}
tasks.named("check") { dependsOn(checkStateComponentOverloads) }
tasks.matching { it.name != "generateStateComponentOverloads" }.configureEach {
    mustRunAfter("generateStateComponentOverloads")
}
