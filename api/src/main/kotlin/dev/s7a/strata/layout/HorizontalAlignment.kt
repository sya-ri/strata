package dev.s7a.strata.layout

/**
 * Horizontal cross-axis placement policy.
 */
public enum class HorizontalAlignment {
    /**
     * Places a child at the start edge.
     */
    Start,

    /**
     * Centers a child horizontally.
     */
    Center,

    /**
     * Places a child at the end edge.
     */
    End,
}
