package dev.s7a.strata.layout

/**
 * Vertical cross-axis placement policy.
 */
public enum class VerticalAlignment {
    /**
     * Places a child at the top edge.
     */
    Top,

    /**
     * Centers a child vertically.
     */
    Center,

    /**
     * Places a child at the bottom edge.
     */
    Bottom,
}
