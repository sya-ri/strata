internal object StrataSkillMarkdown {
    /**
     * Renders the complete standard component catalog from compiled overload counts and shared guidance.
     *
     * @param signatures exact source-form signatures verified against every compiled component overload.
     * @return LF-normalized Markdown with one terminal newline.
     */
    internal fun components(signatures: Map<DocumentedComponent, List<String>>): String =
        markdown(
            """<!-- Generated by :integration:docs:generateStrataSkill. Do not edit. -->

# Component catalog

Strata exposes ${signatures.size} focused standard components from `dev.s7a.strata.component`.
Every Kotlin declaration below is paired with the compiled `strata-api` overload inventory; generation fails when source and binary identities diverge or an undocumented component enters the API.
Use the [component showcase on GitHub]($COMPONENT_GUIDE_URL) for complete compiled examples and Minecraft-verified images.

${signatures.entries.joinToString("\n\n") { (component, overloads) -> component(component, overloads) }}
""",
        )

    /**
     * Renders the modifier and parent-layout-scope catalog from compiled overload counts.
     *
     * @param inventory exact compiled modifier inventory.
     * @param compiledStateAndBindings exact compiled state and binding member fingerprints.
     * @param signatures exact source-form signatures paired with the compiled inventory.
     * @return LF-normalized Markdown with one terminal newline.
     */
    internal fun modifiers(
        inventory: ModifierInventory.Result,
        compiledStateAndBindings: Map<String, List<String>>,
        signatures: KotlinSourceSignatureInventory.Result,
    ): String =
        markdown(
            """<!-- Generated by :integration:docs:generateStrataSkill. Do not edit. -->

# Modifiers and layout scopes

Modifiers are active retained behavior, not a passive settings bag.
Order matters: layout and input elements wrap the behavior that follows them in the chain.
The ${inventory.modifiers.values.sum()} compiled overloads below form ${inventory.modifiers.size} top-level extension groups.

| Extension | Overloads | Category | Use |
| --- | ---: | --- | --- |
${inventory.modifiers.entries.joinToString("\n") { (name, count) -> modifierRow(name, count) }}

## Top-level modifier signatures

${inventory.modifiers.keys.joinToString("\n\n") { name -> signatureGroup(name, signatures.modifiers.getValue(name)) }}

## Parent-layout modifiers

These extensions are available only inside the layout scope that consumes their parent data.
Do not move them to a generic global helper or use them outside a direct child declaration.

| Scope extension | Overloads | Meaning |
| --- | ---: | --- |
${inventory.parentScopeModifiers.entries.joinToString("\n") { (entry, count) -> parentScopeRow(entry, count) }}

### Parent-layout signatures

${inventory.parentScopeModifiers.keys.joinToString("\n\n") { entry -> signatureGroup("${entry.scopeName}.${entry.methodName}", signatures.parentScopeModifiers.getValue(entry)) }}

## Selection guide

- Use `spacing`, `horizontalArrangement`, `verticalArrangement`, and parent alignment to describe sibling structure.
- Use `weight` only for remaining main-axis space and `align` only for a direct-child override.
- Use small `padding` for local insets. A value of 20 or more needs a concrete native-frame or fixed-geometry reason.
- Put images on `imageBackground` when they paint a container; use `Image` when the image is itself a logical child.
- Put reusable actions on modifiers. `Button`, `Tab`, `Checkbox`, `CycleButton`, `Slider`, and list components keep application callbacks out of their component signatures.

## State and binding signatures

The following declarations are extracted from the public state and binding source files that compile into `strata-api`.
Use them to choose ownership and source types; application state remains authoritative.
Members marked `@InternalStrataRuntimeApi` are deliberately omitted from consumer signatures; the collapsed JVM fingerprints retain them only so binary drift still invalidates generation.

${StateBindingDocumentationCatalog.entries.joinToString("\n\n") { entry -> stateBindingGroup(entry, signatures.stateAndBindings.getValue(entry.typeName), compiledStateAndBindings.getValue(entry.typeName)) }}
""",
        )

