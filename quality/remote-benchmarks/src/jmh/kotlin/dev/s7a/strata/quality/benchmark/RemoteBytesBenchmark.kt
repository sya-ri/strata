package dev.s7a.strata.quality.benchmark

import dev.s7a.strata.performance.JmhWorkloadInventory
import dev.s7a.strata.projection.ProjectionType
import dev.s7a.strata.projection.ProjectionValue
import dev.s7a.strata.resource.ResourceId
import dev.s7a.strata.runtime.remote.RemoteFraming
import dev.s7a.strata.runtime.remote.RemoteLimits
import dev.s7a.strata.runtime.remote.RemoteMessage
import dev.s7a.strata.runtime.remote.RemoteMessageCodec
import dev.s7a.strata.runtime.remote.RemoteValueCodec
import org.openjdk.jmh.annotations.Benchmark
import org.openjdk.jmh.annotations.Level
import org.openjdk.jmh.annotations.Param
import org.openjdk.jmh.annotations.Scope
import org.openjdk.jmh.annotations.Setup
import org.openjdk.jmh.annotations.State
import java.io.ByteArrayOutputStream
import java.io.DataOutputStream

/**
 * Immutable generic byte inputs and actual action-message controls, compatible with both target archives.
 * Preparation, independent wire checks, and construction-site inspection belong outside measured codec work.
 * Projection construction and framing are separate controls; action encoding includes its real schema projection.
 */
public open class RemoteBytesBenchmark {
    /**
     * Constructs detached properties from prepared source buffers, independently of wire serialization.
     */
    @Benchmark
    public fun projectionConstruction(scene: Scene): ProjectionValue = scene.constructProjection()

    /**
     * Encodes a prepared immutable value with the actual generic codec.
     */
    @Benchmark
    public fun valueEncode(scene: Scene): ByteArray = scene.encodeValue()

    /**
     * Decodes frozen generic wire bytes without including input encoding.
     */
    @Benchmark
    public fun valueDecode(scene: Scene): ProjectionValue = scene.decodeValue()

    /**
     * Encodes and decodes the prepared generic value in one invocation.
     */
    @Benchmark
    public fun valueRoundTrip(scene: Scene): ProjectionValue = scene.roundTripValue()

    /**
     * Encodes an actual byte-bearing action, including ordinary message-schema projection.
     */
    @Benchmark
    public fun actionEncode(scene: Scene): ByteArray = scene.encodeAction()

    /**
     * Decodes a frozen complete action and validates its schema.
     */
    @Benchmark
    public fun actionDecode(scene: Scene): RemoteMessage = scene.decodeAction()

    /**
     * Round trips an actual action through both ordinary message-codec directions.
     */
    @Benchmark
    public fun actionRoundTrip(scene: Scene): RemoteMessage = scene.roundTripAction()

    /**
     * Frames and assembles frozen action wire bytes, excluding projection and codec work.
     */
    @Benchmark
    public fun actionFraming(scene: Scene): ByteArray = scene.frameAction()

    /**
     * Complete payload and control corpus; near-limit sizes account for each layer's actual header.
     */
    public enum class Corpus {
        Zero,
        Small32,
        Large262144,
        OneMiB,
        NearLimit,
        ManySmall,
        NestedMixed,
        ByteFree,
    }

    /**
     * One worker's immutable inputs; neither codec keeps cross-call output or incoming payload storage.
     * Wire inputs are generated by the independent JDK reference before timing and never mutated.
     */
    @State(Scope.Thread)
    public open class Scene(
        private val limits: RemoteLimits = RemoteLimits(),
    ) {
        /**
         * Includes every small and byte-free control even when it regresses.
         */
        @JvmField
        @Param
        public var corpus: Corpus = Corpus.Zero

        private val codec = RemoteValueCodec(limits)
        private val messages = RemoteMessageCodec(limits)
        private val type = ProjectionType(ResourceId("benchmark", "bytes"))
        private lateinit var payloads: List<ByteArray>
        private lateinit var value: ProjectionValue
        private lateinit var valueWire: ByteArray
        private lateinit var action: RemoteMessage.Action
        private lateinit var actionWire: ByteArray

        /**
         * Generates stable payloads and complete independent wire inputs outside measured operations.
         */
        @Setup(Level.Trial)
        public fun setup() {
            payloads = payloads(5)
            value = project(payloads)
            valueWire = reference(value)
            val emptyAction = RemoteMessage.Action(1, 1, 1, type, ProjectionValue.Bytes(byteArrayOf()))
            val actionHeader = reference(projectAction(emptyAction)).size
            action = RemoteMessage.Action(1, 1, 1, type, project(payloads(actionHeader)))
            actionWire = reference(projectAction(action))
            check(valueWire.size <= limits.messageBytes && actionWire.size <= limits.messageBytes)
        }

        /**
         * Snapshots prepared source arrays as an independent projection-construction control.
         */
        public fun constructProjection(): ProjectionValue = project(payloads)

        /**
         * Returns a fresh complete generic wire snapshot.
         */
        public fun encodeValue(): ByteArray = codec.encode(value)

        /**
         * Publishes a fresh immutable generic result from frozen incoming bytes.
         */
        public fun decodeValue(): ProjectionValue = codec.decode(valueWire)

        /**
         * Uses actual generic encoding and decoding without retaining an earlier result.
         */
        public fun roundTripValue(): ProjectionValue = codec.decode(codec.encode(value))

        /**
         * Returns an ordinary message codec's fresh logical action bytes.
         */
        public fun encodeAction(): ByteArray = messages.encode(action)

        /**
         * Validates and publishes an ordinary action from independent incoming wire bytes.
         */
        public fun decodeAction(): RemoteMessage = messages.decode(actionWire)

        /**
         * Uses both complete logical-message codec directions, excluding fragmentation.
         */
        public fun roundTripAction(): RemoteMessage = messages.decode(messages.encode(action))

        /**
         * Uses fresh real framing owners and closes both after success or failure.
         * Zero is a fixed logical transport timestamp, independent of any performance clock.
         */
        public fun frameAction(): ByteArray {
            var complete: ByteArray? = null
            RemoteFraming(limits).use { sender ->
                RemoteFraming(limits).use { receiver ->
                    sender.send(actionWire) { fragment ->
                        receiver.receive(fragment, 0)?.let { complete = it }
                    }
                }
            }
            return checkNotNull(complete)
        }

        /**
         * Checks every wire byte, defensive output ownership, schema parity, and framing outside timing.
         * Printed payload counts describe the input corpus; they are not measured removed-copy counts.
         */
        public fun verifyWork() {
            check(constructProjection() == value)
            check(encodeValue().contentEquals(valueWire))
            check(decodeValue() == value && roundTripValue() == value)
            check(encodeAction().contentEquals(actionWire))
            check(decodeAction() == action && roundTripAction() == action)
            check(frameAction().contentEquals(actionWire))
            encodeValue().fill(0)
            encodeAction().fill(0)
            check(encodeValue().contentEquals(valueWire) && encodeAction().contentEquals(actionWire))
            if (corpus == Corpus.NearLimit) check(valueWire.size == limits.messageBytes && actionWire.size == limits.messageBytes)
            println("Bytes $corpus: ${payloads.size} payload fields, ${payloads.sumOf { it.size.toLong() }} generic payload bytes; ${valueWire.size} value wire bytes, ${actionWire.size} action wire bytes")
        }

        private fun payloads(header: Int): List<ByteArray> {
            val sizes =
                when (corpus) {
                    Corpus.Zero -> listOf(0)
                    Corpus.Small32 -> listOf(32)
                    Corpus.Large262144 -> listOf(262144)
                    Corpus.OneMiB -> listOf(1048576)
                    Corpus.NearLimit -> listOf(limits.messageBytes - header)
                    Corpus.ManySmall -> List(256) { 32 }
                    Corpus.NestedMixed -> listOf(4096, 32)
                    Corpus.ByteFree -> emptyList()
                }
            return sizes.mapIndexed { field, size -> ByteArray(size) { (it * 31 + field).toByte() } }
        }

        private fun project(payloads: List<ByteArray>): ProjectionValue =
            when (corpus) {
                Corpus.ManySmall -> ProjectionValue.Sequence(payloads.map(ProjectionValue::Bytes))
                Corpus.NestedMixed ->
                    ProjectionValue.Sequence(
                        listOf(
                            ProjectionValue.Text("日本語"),
                            ProjectionValue.Bytes(payloads[0]),
                            ProjectionValue.Sequence(listOf(ProjectionValue.Flag(true), ProjectionValue.Bytes(payloads[1]), ProjectionValue.Integer(Long.MIN_VALUE))),
                            ProjectionValue.Real(-0.0),
                            ProjectionValue.Absent,
                        ),
                    )
                Corpus.ByteFree -> ProjectionValue.Sequence(List(128) { ProjectionValue.Integer(it.toLong()) } + listOf(ProjectionValue.Text("byte-free control"), ProjectionValue.Flag(true)))
                else -> ProjectionValue.Bytes(payloads.single())
            }

        private fun projectAction(action: RemoteMessage.Action): ProjectionValue =
            ProjectionValue.Sequence(
                listOf(
                    ProjectionValue.Integer(4),
                    ProjectionValue.Integer(action.session),
                    ProjectionValue.Integer(action.sequence),
                    ProjectionValue.Integer(action.endpoint),
                    ProjectionValue.Sequence(listOf(ProjectionValue.Text(action.type.name.namespace), ProjectionValue.Text(action.type.name.path), ProjectionValue.Integer(action.type.version.toLong()))),
                    action.value,
                ),
            )

        private fun reference(value: ProjectionValue): ByteArray {
            val bytes = ByteArrayOutputStream()
            DataOutputStream(bytes).use { write(it, value) }
            return bytes.toByteArray()
        }

        private fun write(
            output: DataOutputStream,
            value: ProjectionValue,
        ) {
            when (value) {
                ProjectionValue.Absent -> output.writeByte(0)
                is ProjectionValue.Flag -> {
                    output.writeByte(1)
                    output.writeBoolean(value.value)
                }
                is ProjectionValue.Integer -> {
                    output.writeByte(2)
                    output.writeLong(value.value)
                }
                is ProjectionValue.Real -> {
                    output.writeByte(3)
                    output.writeDouble(value.value)
                }
                is ProjectionValue.Text -> {
                    val bytes = value.value.encodeToByteArray(throwOnInvalidSequence = true)
                    output.writeByte(4)
                    output.writeInt(bytes.size)
                    output.write(bytes)
                }
                is ProjectionValue.Bytes -> {
                    val bytes = value.toByteArray()
                    output.writeByte(5)
                    output.writeInt(bytes.size)
                    output.write(bytes)
                }
                is ProjectionValue.Sequence -> {
                    output.writeByte(6)
                    output.writeInt(value.values.size)
                    value.values.forEach { write(output, it) }
                }
            }
        }
    }

    /**
     * Generated discovery owns the complete fixture; the generic shared launcher needs no special flag.
     */
    public companion object {
        /**
         * Requires all 64 generated combinations and their independent wire/ownership/framing checks.
         */
        @JvmStatic
        public fun verifyWork() {
            check(JmhWorkloadInventory.capture(listOf(RemoteBytesBenchmark::class.java), setOf("avgt")).size == 64)
            for (corpus in Corpus.entries) {
                Scene().apply { this.corpus = corpus }.also {
                    it.setup()
                    it.verifyWork()
                }
            }
        }
    }
}
